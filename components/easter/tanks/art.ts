/* ═══ Спрайты «Броневика» ═══
   Палитра нарочно «консольная», без неона: игра должна читаться как классика,
   а не как продолжение киберпанковой обороны счёта.

   Танк рисуется ОДИН раз смотрящим вверх, остальные стороны — поворот канваса
   на кратный прямому угол: пиксели ложатся в клетки и не мылятся. */
import type { Art, Op } from "../td/pixel";

const OUT = 9;
/** 0–4 — корпус, 5–7 — своя краска типа, 8 — белый, 9 — обводка */
const pal = (a: [string, string, string]) => [
  "#0b0b0b", "#20242c", "#3a4048", "#5c646f", "#8a93a0",
  ...a, "#ffffff", "#000000",
];

export type TankKind = "player" | "grunt" | "swift" | "armor" | "heavy";

