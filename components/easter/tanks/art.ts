/* ═══ Спрайты «Броневика» ═══
   Танк рисуется ОДИН раз — смотрящим вверх. Остальные три стороны получаются
   поворотом канваса на кратный прямому угол: при таком повороте пиксели ложатся
   ровно в клетки, и пиксель-арт не мылится. Четыре комплекта спрайтов ради
   этого держать незачем.

   Пиксельный «язык» переиспользуем из башенной пасхалки — он к ней не привязан. */
import type { Art, Op } from "../td/pixel";

const STEEL = [
  "#05060c", // 0 обводка
  "#1a1f33", // 1 тень
  "#2e3652", // 2 металл
  "#4a5578", // 3 светлый металл
  "#6f7ca8", // 4 блик
];
const OUT = 9;
const pal = (a: [string, string, string]) => [...STEEL, ...a, "#ffffff", "#04050b"];

export type TankKind = "player" | "grunt" | "swift" | "armor";

/** Неон по типу: игрок — циан, остальные — своя тревожная гамма. */
export const TANK_NEON: Record<TankKind, [string, string, string]> = {
  player: ["#0d6f9e", "#35e0ff", "#a5f7ff"],
  grunt: ["#8a5a12", "#e8a33c", "#ffd79a"],
  swift: ["#8f1a86", "#ff2fb8", "#ff9de0"],
  armor: ["#7a2b33", "#ff5a4a", "#ffb3a6"],
};

const W = 16;

/** Общий корпус: гусеницы, коробка, башня и ствол вверх. */
function body(extra: Op[] = []): Op[] {
  const t: Op[] = [];
  // гусеницы по бортам
  t.push(["r", 0, 3, 4, 12, 1], ["r", 12, 3, 4, 12, 1]);
  for (const y of [4, 7, 10, 13]) {
    t.push(["r", 0, y, 4, 1, 3], ["r", 12, y, 4, 1, 3]);
  }
  // корпус
  t.push(["r", 4, 4, 8, 11, 2], ["r", 4, 4, 8, 1, 3], ["r", 5, 6, 1, 8, 3]);
  // башня и ствол
  t.push(["e", 7, 9, 3, 3, 3], ["e", 7, 9, 2, 2, 5], ["p", 7, 9, 6]);
  t.push(["r", 7, 1, 2, 8, 2], ["r", 7, 1, 2, 1, 4]);
  return [...t, ...extra];
}

